def _score_topic(query, topic):
    normalized_query = query.lower()
    return sum(1 for keyword in topic["trigger_keywords"] if keyword.lower() in normalized_query)


def get_legal_guidance(query, language="en"):
    best_topic = None
    best_score = 0

    for topic in LEGAL_KB:
        score = _score_topic(query, topic)
        if score > best_score:
            best_score = score
            best_topic = topic

    if not best_topic:
        fallback = (
            "I don't have a strong match for that legal topic yet. Please contact the nearest District Legal Services Authority or a trusted local legal aid center for guidance."
            if language == "en"
            else "Is kanooni vishay par mere paas abhi mazboot match nahi hai. Kripya najdeeki District Legal Services Authority ya kisi bharosemand legal aid kendra se sampark karein."
        )
        return {
            "topic": "General legal help",
            "answer": fallback,
            "law_reference": "District Legal Services Authority support",
            "confidence": 0.0,
        }

    confidence = min(0.92, 0.35 + (best_score * 0.18))
    return {
        "topic": best_topic["topic"],
        "answer": best_topic["answer_hi"] if language == "hi" else best_topic["answer_en"],
        "law_reference": best_topic["law_reference"],
        "confidence": round(confidence, 2),
    }
